#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
BRANCH="feat/amri-stage3-composite-context"
STAGE2_BRANCH="feat/amri-stage2-core"
EXPECTED_BASE="0061795bb63c5455d9abb8e3ea6da22db671fd26"
EXPECTED_ORIGIN="git@github.com:israelsantiago/supplier-rfq-rust.git"
[[ "$(git branch --show-current)" == "$BRANCH" ]] || { echo "ERRO: finalize deve rodar na branch $BRANCH." >&2; exit 2; }
[[ "$(git remote get-url origin)" == "$EXPECTED_ORIGIN" ]] || { echo "ERRO: origin inesperado." >&2; exit 2; }
[[ "$(git rev-parse HEAD)" == "$EXPECTED_BASE" ]] || { echo "ERRO: Stage 3 deve ser finalizada a partir do baseline Stage 2 exato; HEAD foi alterado." >&2; exit 2; }
REMOTE_STAGE2="$(git ls-remote origin "refs/heads/$STAGE2_BRANCH" | awk 'NR == 1 {print $1}')"
[[ "$REMOTE_STAGE2" == "$EXPECTED_BASE" ]] || { echo "ERRO: branch remota Stage 2 não corresponde ao baseline publicado; esperado=$EXPECTED_BASE remoto=${REMOTE_STAGE2:-<ausente>}." >&2; exit 2; }
# Mutation testing is intentionally deferred to the final AMRI campaign.
# Missing or stale fingerprints are regenerated by their real gates; they are never
# treated as a pass. The mutation campaign is not an intermediate prerequisite.
if ! bash scripts/amri-stage3-gate-state.sh verify context-verify; then
  echo "Stage 3A context-verify ausente/desatualizado; reexecutando verificação funcional."
  bash scripts/verify-amri-stage3-context.sh
fi
if ! bash scripts/amri-stage3-gate-state.sh verify context-coverage; then
  echo "Stage 3A context-coverage ausente/desatualizado; reexecutando cobertura obrigatória."
  echo "Este fluxo não executa mutation testing nem inicia Testcontainers."
  bash scripts/coverage-amri-stage3-context.sh
fi
if ! bash scripts/amri-stage3-gate-state.sh verify factstr-integration; then
  echo "Gate FACTSTR/PostgreSQL ausente/desatualizado; reexecutando a integração obrigatória."
  echo "Esta recuperação inicia Testcontainers; Docker precisa estar operacional."
  bash scripts/verify-amri-stage3-factstr.sh
fi
for gate in context-verify context-coverage factstr-integration; do
  bash scripts/amri-stage3-gate-state.sh verify "$gate"
done

REMOTE_REF_OUTPUT="$(git ls-remote --heads origin "refs/heads/$BRANCH")"
[[ -z "$REMOTE_REF_OUTPUT" ]] || { echo "ERRO: branch remota Stage 3 já existe; não será sobrescrita." >&2; exit 2; }

printf '\n== 1. Regressão integral do repositório ==\n'
bash scripts/verify-rpu-boundaries.sh
bash scripts/verify-application-state-boundary.sh
bash scripts/verify-functional-core-test-isolation.sh
bash scripts/verify-openapi.sh
sh scripts/verify-mermaid-diagrams.sh
bash scripts/verify-documentation-current-state.sh
bash scripts/verify-amri-core-boundaries.sh

printf '\n== 2. Atualizar documentação com evidências dos gates aprovados ==\n'
python3 scripts/update-amri-stage3-docs.py
bash scripts/verify-documentation-current-state.sh
sh scripts/verify-mermaid-diagrams.sh

printf '\n== 3. Verificar integridade documental e diff ==\n'
git diff --check

EXPECTED_PATHS=(
  src/application_state.rs
  src/application_state/atomic_interaction/context.rs
  src/application_state/atomic_interaction/state_port.rs
  src/application_state/atomic_interaction/fake.rs
  src/application_state/atomic_interaction/mod.rs
  src/application_state/atomic_interaction/factstr.rs
  tests/amri_factstr_state.rs
  docs/architecture/amri/stage-3-composite-context-state-port.md
  docs/architecture/amri/README.md
  docs/architecture/amri/implementation-plan.md
  docs/architecture/adr/0034-atomic-multi-rpu-interaction.md
  docs/testing/architecture-evidence.md
  scripts/update-amri-stage3-docs.py
  scripts/amri-stage3-gate-state.sh
  scripts/verify-amri-stage3-context.sh
  scripts/check-amri-stage3-context-coverage.py
  scripts/coverage-amri-stage3-context.sh
  scripts/mutate-amri-stage3-context.sh
  scripts/verify-amri-stage3-factstr.sh
  scripts/finalize-amri-stage3.sh
)
assert_allowed() {
  local path="$1" expected
  for expected in "${EXPECTED_PATHS[@]}"; do [[ "$path" == "$expected" ]] && return 0; done
  echo "ERRO: arquivo fora da allowlist Stage 3: $path" >&2
  exit 2
}
printf '\n== 4. Verificar allowlist Stage 3 ==\n'
while IFS= read -r -d '' path; do assert_allowed "$path"; done < <(git diff --cached --name-only -z HEAD)
while IFS= read -r -d '' path; do assert_allowed "$path"; done < <(git diff --name-only -z)
while IFS= read -r -d '' path; do assert_allowed "$path"; done < <(git ls-files --others --exclude-standard -z)
for path in "${EXPECTED_PATHS[@]}"; do [[ -f "$path" ]] || { echo "ERRO: arquivo esperado ausente: $path" >&2; exit 2; }; done

git add -- "${EXPECTED_PATHS[@]}"
git diff --cached --check
printf '\n--- git status --short ---\n'
git status --short
printf '\n--- git diff --cached --stat ---\n'
git diff --cached --stat
printf '\n--- git diff --cached --name-status ---\n'
git diff --cached --name-status
printf '\n========== DIFF STAGED COMPLETO ==========\n'
git --no-pager diff --cached --no-ext-diff --
printf '\nPara criar o commit e fazer push sem force, digite PUBLICAR: '
read -r confirmation
if [[ "$confirmation" != "PUBLICAR" ]]; then
  echo "Interrompido. Arquivos permanecem staged; nenhum commit/push foi feito."
  exit 0
fi

git commit -m "feat(amri): add composite context and atomic state port"
LOCAL_SHA="$(git rev-parse HEAD)"
if ! git push --set-upstream origin "$BRANCH"; then
  echo "ERRO: commit local criado, push falhou; preserve o commit $LOCAL_SHA e tente push sem recriar." >&2
  exit 3
fi
REMOTE_SHA="$(git ls-remote origin "refs/heads/$BRANCH" | awk 'NR == 1 {print $1}')"
[[ "$REMOTE_SHA" == "$LOCAL_SHA" ]] || { echo "ERRO: SHA remoto difere do local. Local=$LOCAL_SHA Remote=${REMOTE_SHA:-<ausente>}" >&2; exit 3; }
[[ -z "$(git status --porcelain=v1 --untracked-files=all)" ]] || { echo "ERRO: worktree não ficou limpo após o push." >&2; git status --short; exit 3; }
echo "PASS: Stage 3 commit/push verificado."
echo "Branch: $BRANCH"
echo "Commit: $LOCAL_SHA"
echo "Remote SHA: $REMOTE_SHA"
echo "Worktree: CLEAN"
